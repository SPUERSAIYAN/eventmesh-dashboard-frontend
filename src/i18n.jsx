export function translateText(language, text) {
  if (language !== "zh" || text == null) return text;
  const value = String(text);
  if (zh[value]) return zh[value];
  const patterns = [
    [/^Started (.+)$/, "已启动 $1"],
    [/^Updated (.+) to (.+)$/, "已将 $1 更新为 $2"],
    [/^Created topic (.+)$/, "已创建主题 $1"],
    [/^Deployed (.+) consumer group$/, "已部署消费组 $1"],
    [/^Created (.+) connector$/, "已创建连接器 $1"],
  ];
  const match = patterns.find(([pattern]) => pattern.test(value));
  return match ? value.replace(match[0], match[1]) : value;
}

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [language, setLanguage] = useState(() => window.localStorage.getItem("eventmesh-language") || (window.navigator.language?.toLowerCase().startsWith("zh") ? "zh" : "en"));
  useEffect(() => {
    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  }, [language]);
  const value = useMemo(() => ({
    language,
    locale: language === "zh" ? "zh-CN" : "en-US",
    t: (text) => translateText(language, text),
    toggleLanguage: () => setLanguage((current) => {
      const next = current === "en" ? "zh" : "en";
      window.localStorage.setItem("eventmesh-language", next);
      document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
      return next;
    }),
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
